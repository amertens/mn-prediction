# =============================================================================
# R/single_var_ablation.R
#
# Per-variable permutation importance. Provides finer-grained alternative to
# the domain-level ablation in R/domain_ablation.R, returning the AUC drop
# associated with permuting each individual predictor.
#
# Used by the dashboard to surface the "top 5 factors driving risk" in each
# country × outcome model. Complementary to the SHAP attributions in
# R/shap_explanations.R: SHAP gives per-district direction and magnitude;
# this gives population-level importance ranking.
# =============================================================================


#' Per-variable permutation importance
#'
#' For each predictor, shuffles its column once (across all observations)
#' and measures the AUC (or RMSE) drop relative to the unpermuted baseline.
#' Larger drops = more important. Cheaper than SHAP since predictions are
#' generated by the existing SL without refitting.
#'
#' @param outcome_data Output from build_outcome_dataset()
#' @param sl_fit Output from fit_mlr3_models()
#' @param cc Country config
#' @param oc Outcome config
#' @param top_n Return only the top-N variables (default 30); NULL returns all
#' @param n_perm Number of permutation replicates per variable (default 3)
#' @return data.frame with variable, mean_auc_drop (or rmse_increase), country, outcome
run_single_var_ablation <- function(outcome_data, sl_fit, cc, oc,
                                      top_n = 30L, n_perm = 3L) {

  fit_obj <- sl_fit$bin_fit %||% sl_fit$cont_fit
  if (is.null(fit_obj)) return(data.frame())

  use_binary <- !is.null(sl_fit$bin_fit)
  Xvars <- fit_obj$Xvars %||% outcome_data$Xvars
  if (is.null(Xvars) || length(Xvars) == 0) return(data.frame())

  d <- outcome_data$data
  Y <- as.double(unclass(fit_obj$res$Y))
  # In-sample baseline to match the in-sample permuted predictions below
  # (yhat_full is now out-of-fold; fall back to it for pre-existing fits).
  yhat_full <- as.double(unclass(fit_obj$res$yhat_insample %||% fit_obj$res$yhat_full))
  baseline <- compute_perf_metrics(Y, yhat_full, use_binary)
  baseline_metric <- if (use_binary) baseline$auc else baseline$rmse

  cat(sprintf("[single_var] %s — %s | baseline %s = %.3f | testing %d variables\n",
              cc$country, oc$tag,
              if (use_binary) "AUC" else "RMSE",
              baseline_metric, length(Xvars)))

  # For computational efficiency, we restrict to variables actually used in
  # the model (those in fit_obj$Xvars). For each, we permute and call the
  # existing prediction wrapper from the SL.
  if (is.null(fit_obj$sl_fit) || is.null(fit_obj$train_data)) {
    cat("  [single_var] sl_fit or train_data missing, skipping\n")
    return(data.frame())
  }

  newdata <- as.data.frame(fit_obj$train_data)

  results <- list()
  for (v in Xvars) {
    if (!v %in% colnames(newdata)) next

    drop_rep <- numeric(n_perm)
    for (k in seq_len(n_perm)) {
      shuffled <- newdata
      shuffled[[v]] <- sample(shuffled[[v]])
      # Prefer mlr3superlearner's own predict when available. Calling the
      # generic predict() on the wrapper has no S3 method (silent failure),
      # and the wrapper's $predict aligns newdata to covars only and strips
      # the CV group column (cluster_id) that mlr3_fit$x expects — so it
      # errors with "undefined columns selected". `shuffled` comes from
      # fit_obj$train_data and already contains cluster_id, so we can call
      # mlr3_fit directly.
      pred_perm <- tryCatch({
        mlr3_obj <- fit_obj$sl_fit$mlr3_fit
        if (!is.null(mlr3_obj)) {
          as.numeric(stats::predict(mlr3_obj, shuffled))
        } else {
          as.numeric(fit_obj$sl_fit$predict(shuffled))
        }
      }, error = function(e) rep(NA_real_, nrow(shuffled)))

      if (all(is.na(pred_perm))) {
        drop_rep[k] <- NA_real_
        next
      }
      m <- compute_perf_metrics(Y, pred_perm, use_binary)
      drop_rep[k] <- if (use_binary) baseline$auc - m$auc
                      else m$rmse - baseline$rmse
    }

    results[[v]] <- data.frame(
      variable    = v,
      drop_mean   = mean(drop_rep, na.rm = TRUE),
      drop_sd     = sd(drop_rep, na.rm = TRUE),
      n_perm      = n_perm,
      stringsAsFactors = FALSE
    )
  }

  out <- do.call(rbind, results)
  if (is.null(out) || nrow(out) == 0) return(data.frame())

  out <- out[order(-out$drop_mean), ]
  out$rank <- seq_len(nrow(out))
  out$country <- cc$country
  out$outcome <- oc$tag

  if (!is.null(top_n)) {
    out <- out[seq_len(min(top_n, nrow(out))), ]
  }

  out
}
