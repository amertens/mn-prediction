# =============================================================================
# R/merge_external.R
#
# Merge externally-sourced Admin-2 level predictors (CHIRPS, WorldPop, MAP,
# HarvestStat, SoilGrids, etc.) into individual-level survey data.
#
# The external predictors are at Admin-2 level (one value per district).
# This function joins them to individual survey records by matching on
# the Admin2 column, creating area-level contextual variables for each
# individual observation.
# =============================================================================

#' Merge cached external predictors into individual-level data
#'
#' Loads the pre-computed external predictor RDS file for a country
#' (generated by scripts/download_external_predictors.R) and left-joins
#' it to the individual-level merged data by Admin2 name.
#'
#' Uses fuzzy matching (agrep) for Admin2 names that don't match exactly,
#' since GADM names may differ slightly from survey Admin2 names.
#'
#' @param merged_data The merged individual-level data frame
#' @param cc Country config
#' @param cache_dir Path to the external predictor cache directory
#' @return The merged data with additional external predictor columns
merge_external_predictors <- function(merged_data, cc,
                                       cache_dir = here::here("data", "external_cache")) {

  country_lower <- tolower(gsub(" ", "_", cc$country))
  rds_file <- file.path(cache_dir, paste0(country_lower, "_external_predictors.rds"))

  if (!file.exists(rds_file)) {
    cat(sprintf("[merge_ext] No external predictors found for %s at %s\n",
                cc$country, rds_file))
    return(merged_data)
  }

  ext <- readRDS(rds_file)
  cat(sprintf("[merge_ext] Loading %d external predictors for %s (%d Admin-2 areas)\n",
              ncol(ext) - 2, cc$country, nrow(ext)))  # -2 for Admin1, Admin2

  # Identify predictor columns (everything except Admin1, Admin2)
  pred_cols <- setdiff(colnames(ext), c("Admin1", "Admin2"))

  # Drop columns that are all NA (failed downloads)
  non_na_cols <- pred_cols[sapply(pred_cols, function(col) !all(is.na(ext[[col]])))]
  cat(sprintf("[merge_ext] %d/%d predictor columns have data\n",
              length(non_na_cols), length(pred_cols)))

  if (length(non_na_cols) == 0) {
    cat("[merge_ext] No valid predictors — skipping merge\n")
    return(merged_data)
  }

  ext_clean <- ext[, c("Admin2", non_na_cols), drop = FALSE]

  # ── Match Admin2 names ──
  # Survey Admin2 names may differ from GADM names (spelling, accents, etc.)
  admin2_col <- cc$admin2_col
  if (!admin2_col %in% colnames(merged_data)) {
    cat(sprintf("[merge_ext] Admin2 column '%s' not in merged data — skipping\n", admin2_col))
    return(merged_data)
  }

  survey_admin2 <- unique(merged_data[[admin2_col]])
  survey_admin2 <- survey_admin2[!is.na(survey_admin2)]
  ext_admin2    <- ext_clean$Admin2

  # Build name mapping: survey name → external name
  name_map <- setNames(rep(NA_character_, length(survey_admin2)), survey_admin2)

  # Exact matches first
  for (nm in survey_admin2) {
    if (nm %in% ext_admin2) {
      name_map[nm] <- nm
    }
  }

  # Fuzzy match for unmatched
  unmatched <- names(name_map[is.na(name_map)])
  if (length(unmatched) > 0) {
    for (nm in unmatched) {
      fuzzy <- agrep(nm, ext_admin2, max.distance = 0.2, value = TRUE)
      if (length(fuzzy) == 1) {
        name_map[nm] <- fuzzy
      } else if (length(fuzzy) > 1) {
        # Pick closest by nchar difference
        dists <- abs(nchar(fuzzy) - nchar(nm))
        name_map[nm] <- fuzzy[which.min(dists)]
      }
    }
  }

  n_matched <- sum(!is.na(name_map))
  n_total   <- length(survey_admin2)
  cat(sprintf("[merge_ext] Matched %d/%d Admin-2 names (%d fuzzy)\n",
              n_matched, n_total, sum(!is.na(name_map)) - sum(survey_admin2 %in% ext_admin2)))

  if (n_matched == 0) {
    cat("[merge_ext] No Admin-2 matches — skipping merge\n")
    return(merged_data)
  }

  # Create merge key in individual data
  merged_data$`.ext_admin2` <- name_map[merged_data[[admin2_col]]]

  # Rename Admin2 in ext_clean to match merge key
  ext_merge <- ext_clean
  colnames(ext_merge)[colnames(ext_merge) == "Admin2"] <- ".ext_admin2"

  # ── Deduplicate: GADM Admin-2 polygons can have duplicate names ──────────

  # (e.g., "Lake Malawi" appears 8 times as separate shoreline polygons).
  # A many-to-many merge would create a cartesian product, inflating rows.
  # Strategy: for each duplicate Admin2, average the numeric predictor values.
  n_ext_before <- nrow(ext_merge)
  dup_keys <- ext_merge$.ext_admin2[duplicated(ext_merge$.ext_admin2)]
  if (length(dup_keys) > 0) {
    cat(sprintf("[merge_ext] WARNING: %d duplicate Admin2 names in external data: %s\n",
                length(unique(dup_keys)),
                paste(unique(dup_keys), collapse = ", ")))
    cat("[merge_ext] Deduplicating by averaging numeric values per Admin2...\n")

    # Split into numeric and non-numeric columns
    num_cols <- names(ext_merge)[sapply(ext_merge, is.numeric)]
    ext_merge <- ext_merge |>
      dplyr::group_by(.ext_admin2) |>
      dplyr::summarise(dplyr::across(dplyr::all_of(num_cols), ~ mean(.x, na.rm = TRUE)),
                       .groups = "drop") |>
      as.data.frame()
    cat(sprintf("[merge_ext] Deduplicated: %d -> %d unique Admin2 areas\n",
                n_ext_before, nrow(ext_merge)))
  }

  # Left join (now guaranteed 1:many at most — one ext row per Admin2)
  n_before <- ncol(merged_data)
  n_rows_before <- nrow(merged_data)
  merged_data <- merge(merged_data, ext_merge, by = ".ext_admin2",
                       all.x = TRUE, sort = FALSE)
  if (nrow(merged_data) != n_rows_before) {
    warning(sprintf("[merge_ext] Row count changed during merge: %d -> %d! Possible many-to-many join.",
                    n_rows_before, nrow(merged_data)))
  }

  # Clean up merge key
  merged_data$`.ext_admin2` <- NULL

  n_new <- ncol(merged_data) - n_before + 1  # +1 because we removed .ext_admin2
  n_with_data <- sum(!is.na(merged_data[[non_na_cols[1]]]))
  cat(sprintf("[merge_ext] Added %d predictor columns, %d/%d rows with external data\n",
              n_new, n_with_data, nrow(merged_data)))

  # ── Also merge DHS Admin-2 indicators if available ──
  # These are pre-built wide-format RDS files from DHS_admin2_aggregation.R
  # and DHS_custom_admin2_indicators.R, stored in data/DHS/clean/.
  dhs_dir <- here::here("data", "DHS", "clean")
  dhs_country_name <- cc$country  # e.g., "Ghana", "Gambia"

  # Map country to DHS year — prefer config, fall back to hardcoded
  dhs_year <- cc$dhs_year
  if (is.null(dhs_year)) {
    dhs_years <- c("Gambia" = 2019L, "Ghana" = 2014L,
                   "Sierra Leone" = 2013L, "Malawi" = 2015L)
    dhs_year <- dhs_years[dhs_country_name]
  }

  if (!is.na(dhs_year) && dir.exists(dhs_dir)) {
    dhs_admin2 <- tryCatch(
      load_dhs_admin2(dhs_dir, dhs_country_name, dhs_year, merge_col = "Admin2"),
      error = function(e) {
        cat(sprintf("[merge_ext] DHS Admin-2 load failed: %s\n", e$message))
        NULL
      }
    )

    if (!is.null(dhs_admin2) && nrow(dhs_admin2) > 0) {
      # Build name mapping (same fuzzy matching approach)
      dhs_admin2_names <- dhs_admin2$Admin2
      survey_admin2_names <- unique(merged_data[[admin2_col]])
      survey_admin2_names <- survey_admin2_names[!is.na(survey_admin2_names)]

      dhs_name_map <- setNames(rep(NA_character_, length(survey_admin2_names)), survey_admin2_names)
      for (nm in survey_admin2_names) {
        if (nm %in% dhs_admin2_names) {
          dhs_name_map[nm] <- nm
        } else {
          fuzzy <- agrep(nm, dhs_admin2_names, max.distance = 0.2, value = TRUE)
          if (length(fuzzy) >= 1) dhs_name_map[nm] <- fuzzy[1]
        }
      }

      n_dhs_matched <- sum(!is.na(dhs_name_map))
      cat(sprintf("[merge_ext] DHS Admin-2: matched %d/%d areas\n",
                  n_dhs_matched, length(survey_admin2_names)))

      if (n_dhs_matched > 0) {
        merged_data$`.dhs_admin2` <- dhs_name_map[merged_data[[admin2_col]]]
        dhs_merge <- dhs_admin2
        colnames(dhs_merge)[colnames(dhs_merge) == "Admin2"] <- ".dhs_admin2"

        # Deduplicate DHS admin2 data (same logic as external predictors)
        dhs_dup_keys <- dhs_merge$.dhs_admin2[duplicated(dhs_merge$.dhs_admin2)]
        if (length(dhs_dup_keys) > 0) {
          cat(sprintf("[merge_ext] DHS Admin-2 has %d duplicate names — deduplicating\n",
                      length(unique(dhs_dup_keys))))
          dhs_num_cols <- names(dhs_merge)[sapply(dhs_merge, is.numeric)]
          dhs_merge <- dhs_merge |>
            dplyr::group_by(.dhs_admin2) |>
            dplyr::summarise(dplyr::across(dplyr::all_of(dhs_num_cols),
                                            ~ mean(.x, na.rm = TRUE)),
                             .groups = "drop") |>
            as.data.frame()
        }

        n_before_dhs <- ncol(merged_data)
        n_rows_before_dhs <- nrow(merged_data)
        merged_data <- merge(merged_data, dhs_merge, by = ".dhs_admin2",
                             all.x = TRUE, sort = FALSE)
        if (nrow(merged_data) != n_rows_before_dhs) {
          warning(sprintf("[merge_ext] DHS merge changed row count: %d -> %d!",
                          n_rows_before_dhs, nrow(merged_data)))
        }
        merged_data$`.dhs_admin2` <- NULL
        n_dhs_new <- ncol(merged_data) - n_before_dhs + 1
        cat(sprintf("[merge_ext] Added %d DHS Admin-2 predictor columns\n", n_dhs_new))
      }
    }
  }

  merged_data
}


#' Get the survey year for a country config
#'
#' Maps country names to their micronutrient survey data collection years.
#' Used by the external data pipeline to select temporally appropriate
#' predictor data.
#'
#' @param cc Country config
#' @return Integer survey year
get_survey_year <- function(cc) {
  # Prefer survey_year from config (centralized source of truth)
  if (!is.null(cc$survey_year)) return(as.integer(cc$survey_year))

  # Fallback: hardcoded mapping (kept for backward compatibility)
  # Fieldwork dates from survey reports:
  #   Gambia GMNS:  13 Mar – 4 May 2018
  #   Ghana GMS:    27 Apr – 9 Jun 2017
  #   Sierra Leone SLMS: 11 Nov – 2 Dec 2013
  #   Malawi MNS:   8 Dec 2015 – 16 Feb 2016
  survey_years <- c(
    "Gambia"       = 2018L,
    "Ghana"        = 2017L,
    "Sierra Leone" = 2013L,
    "Malawi"       = 2016L
  )
  yr <- survey_years[cc$country]
  if (is.na(yr)) {
    warning(sprintf("No survey year defined for %s — using 2017", cc$country))
    yr <- 2017L
  }
  yr
}
