# =============================================================================
# Module: Côte d'Ivoire Out-of-Sample Predictions
# =============================================================================
# Demonstrates the framework's ability to predict micronutrient deficiency
# prevalence in countries without direct biomarker survey data.
#
# Côte d'Ivoire is used as the OOS target because (a) it has external
# predictor data available (CHIRPS, MAP, GEE rasters, etc.) and (b) it has
# no biomarker survey in the training set.

mod_oos_civ_ui <- function(id) {
  ns <- NS(id)

  layout_columns(
    col_widths = 12,

    div(
      class = "alert alert-info",
      style = "margin-bottom: 1em;",
      h5(bsicons::bs_icon("globe2"),
         " Out-of-sample prediction: Côte d'Ivoire",
         style = "margin-top: 0;"),
      p("Côte d'Ivoire was not in the training data. These predictions are ",
        "generated by applying the multi-country pooled model — trained on ",
        "Gambia, Ghana, Sierra Leone, and Malawi — to Côte d'Ivoire's ",
        "external predictor data. They demonstrate how the framework could ",
        "provide screening estimates for unsurveyed countries while a ",
        "biomarker survey is being planned.")
    ),

    layout_sidebar(
      sidebar = sidebar(
        width = 280,
        title = "Outcome",
        selectInput(ns("outcome"), NULL,
                    choices = c("Vitamin A (children)" = "child_vitA",
                                "Vitamin A (women)"   = "women_vitA",
                                "Iron (children)"     = "child_iron",
                                "Iron (women)"        = "women_iron"),
                    selected = "women_iron"),
        hr(),
        htmlOutput(ns("summary"))
      ),

      card(
        full_screen = TRUE,
        card_header("Predicted prevalence — Côte d'Ivoire (out-of-sample)"),
        card_body(
          padding = 0,
          leafletOutput(ns("map"), height = "500px")
        )
      )
    ),

    card(
      card_header("District-level predictions with uncertainty"),
      card_body(
        reactableOutput(ns("table")),
        downloadButton(ns("download"), "Download CSV",
                        class = "btn-sm btn-outline-primary",
                        style = "margin-top: 8px;"),
        methods_note(
          "These predictions are produced by training a pooled elastic-net ",
          "model on the four survey countries' Admin-2 prevalence estimates ",
          "and applying it to Côte d'Ivoire's matching external predictor ",
          "values. Uncertainty is conformal, calibrated using leave-one-out ",
          "residuals from the training set, with weighting to account for ",
          "covariate shift between training and target countries. ",
          tags$br(), tags$br(),
          "These predictions should be treated as screening estimates ",
          "rather than definitive prevalence: they are intended to support ",
          "the planning of a biomarker survey (e.g., identifying districts ",
          "to oversample) rather than to replace one. The leave-one-country-out ",
          "(LOCO) cross-validation in the underlying pipeline shows that ",
          "model performance drops substantially when applied to a new ",
          "country (LOCO AUC 0.50–0.73), so individual district predictions ",
          "should be interpreted alongside the conformal interval, not as ",
          "point estimates. ",
          tags$br(), tags$br(),
          "The OOS predictions in the current pipeline release use only ",
          "the GEE raster variables that are available across all countries. ",
          "An upgrade to use the full external predictor set (CHIRPS, ",
          "WorldPop, MAP, SoilGrids, etc.) is planned and will substantially ",
          "improve performance — see the project's ",
          tags$em("RA_tasks_temporal_alignment.md"), " for status."
        )
      )
    )
  )
}


mod_oos_civ_server <- function(id) {
  moduleServer(id, function(input, output, session) {
    ns <- session$ns

    oos_data <- reactive({
      req(input$outcome)
      preds <- oos_civ$predictions
      if (is.null(preds) || nrow(preds) == 0) return(NULL)
      preds[preds$outcome == input$outcome, , drop = FALSE]
    })

    output$summary <- renderUI({
      df <- oos_data()
      if (is.null(df) || nrow(df) == 0) {
        return(div(class = "alert alert-warning",
                    "No OOS predictions available for this outcome. The ",
                    "underlying pipeline target may not have been built yet."))
      }
      mean_prev <- mean(df$pred_prev, na.rm = TRUE)
      tagList(
        h6("Côte d'Ivoire summary", style = "margin-top: 0;"),
        p(strong("Districts: "), nrow(df)),
        p(strong("Mean predicted prevalence: "),
          fmt_pct(mean_prev)),
        p(em("Treat as screening estimate."),
          style = "color: #888; font-size: 0.85em;")
      )
    })

    output$map <- renderLeaflet({
      df <- oos_data()
      bnd <- oos_civ$boundaries
      req(df, bnd)

      joined <- merge(bnd, df[, c("Admin2", "pred_prev", "ci_lo", "ci_hi")],
                      by = "Admin2", all.x = TRUE, sort = FALSE)

      pal <- colorNumeric("YlOrRd",
                          domain = range(joined$pred_prev, na.rm = TRUE),
                          na.color = "#cccccc")

      labels <- sprintf(
        "<strong>%s</strong><br/>%s<br/>Predicted: %s<br/>95%% CI: [%s, %s]",
        joined$Admin2,
        ifelse(is.na(joined$Admin1), "", joined$Admin1),
        fmt_pct(joined$pred_prev),
        fmt_pct(joined$ci_lo),
        fmt_pct(joined$ci_hi)
      ) |> lapply(HTML)

      leaflet(joined) |>
        addProviderTiles(providers$CartoDB.Positron) |>
        addPolygons(
          fillColor = pal(joined$pred_prev),
          fillOpacity = 0.75,
          color = "white",
          weight = 1,
          highlightOptions = highlightOptions(
            weight = 3, color = "#333", bringToFront = TRUE
          ),
          label = labels
        ) |>
        addLegend(pal = pal, values = joined$pred_prev,
                  title = "Predicted prevalence",
                  position = "bottomright",
                  labFormat = labelFormat(transform = function(x) round(x * 100, 1),
                                            suffix = "%"))
    })

    output$table <- renderReactable({
      df <- oos_data()
      req(df)
      out <- df[, c("Admin1", "Admin2", "pred_prev", "ci_lo", "ci_hi")]
      out <- out[order(-out$pred_prev), ]

      reactable(
        out,
        compact = TRUE, striped = TRUE,
        searchable = TRUE, defaultPageSize = 12,
        columns = list(
          Admin1 = colDef(name = "Region"),
          Admin2 = colDef(name = "District"),
          pred_prev = colDef(name = "Predicted",
                              format = colFormat(percent = TRUE, digits = 1)),
          ci_lo = colDef(name = "95% CI low",
                          format = colFormat(percent = TRUE, digits = 1)),
          ci_hi = colDef(name = "95% CI high",
                          format = colFormat(percent = TRUE, digits = 1))
        )
      )
    })

    output$download <- downloadHandler(
      filename = function() {
        sprintf("oos_civ_%s_%s.csv", input$outcome, Sys.Date())
      },
      content = function(file) {
        write.csv(oos_data(), file, row.names = FALSE)
      }
    )

  })
}
